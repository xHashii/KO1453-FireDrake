"""Build ONLY zone-21 world rows from the owner's 0002_data.zip. Never execute the dump.
Use --check to verify committed generated SQL and review manifest against the archive.
"""
import collections
import hashlib
import io
import json
import re
import sys
import zipfile
from pathlib import Path
from audit_world_npcs import load_tables

ROOT=Path(__file__).resolve().parents[1]
ALLOW={'K_NPC','K_MONSTER','K_NPCPOS','K_OBJECTPOS'}


def parse_values(text):
    values=[];i=0
    while i<len(text):
        while i<len(text) and text[i].isspace():i+=1
        if text[i]=="'":
            i+=1;value=''
            while i<len(text):
                if text[i]=='\\':
                    i+=1;value+={'n':'\n','r':'\r','t':'\t','0':'\0'}.get(text[i],text[i]);i+=1
                elif text[i]=="'":
                    i+=1
                    if i<len(text) and text[i]=="'":value+="'";i+=1
                    else:break
                else:value+=text[i];i+=1
        else:
            end=text.find(',',i);end=len(text) if end<0 else end
            raw=text[i:end].strip();i=end
            value=None if raw=='NULL' else float(raw) if any(c in raw for c in '.eE') else int(raw)
        values.append(value)
        while i<len(text) and text[i].isspace():i+=1
        if i<len(text):
            if text[i]!=',':raise ValueError('Invalid value separator')
            i+=1
    return values


def source_rows():
    with zipfile.ZipFile(ROOT/'0002_data.zip') as z:
        info=z.getinfo('0002_data.sql')
        if info.file_size>300_000_000:raise ValueError('Unexpectedly large SQL member')
        with z.open(info) as member:
            text=[line.rstrip('\r\n') for line in io.TextIOWrapper(member,encoding='utf-8-sig') if any('`'+table+'`' in line[:55] for table in ALLOW)]
    result={t:[] for t in ALLOW}
    pattern=re.compile(r'INSERT IGNORE INTO `(K_NPC|K_MONSTER|K_NPCPOS|K_OBJECTPOS)` \((.*?)\) VALUES \((.*)\);$')
    for line in text:
        match=pattern.fullmatch(line)
        if not match:continue
        columns=re.findall(r'`([^`]+)`',match[2]);values=parse_values(match[3])
        if len(columns)!=len(values):raise ValueError('Column/value count mismatch')
        result[match[1]].append(dict(zip(columns,values)))
    return result


def literal(value):
    if value is None:return 'NULL'
    if isinstance(value,str):
        # Current imported world names/paths contain no MySQL-mode-sensitive escapes.
        if any(c in value for c in ('\\','\0','\r','\n')):raise ValueError('Unexpected escaped world value')
        return "'"+value.replace("'","''")+"'"
    return str(value)


def build():
    source=source_rows();base=load_tables()
    schemas={t:[r[1] for r in base.execute('PRAGMA table_info('+t+')')] for t in ALLOW}
    spawns=[r for r in source['K_NPCPOS'] if r['ZoneID']==21]
    objects=[r for r in source['K_OBJECTPOS'] if r['ZoneID']==21]
    npc_ids={r['NpcID'] for r in spawns if r['ActType']>=100}
    # Object proxies: import definitions only where they actually exist in source.
    available_npcs={r['sSid'] for r in source['K_NPC']}
    object_ids={r['sIndex'] if r['Type'] in (1,2,3,8,9) else r['ControlNpcID'] for r in objects if r['Type']!=5}
    npc_ids|=object_ids&available_npcs
    monster_ids={r['NpcID'] for r in spawns if r['ActType']<100}
    baseline={r[0]:dict(zip([c[1] for c in base.execute('PRAGMA table_info(K_MONSTER)')],r)) for r in base.execute('SELECT * FROM K_MONSTER')}
    fallbacks={1056:1052,1057:1003,1058:1054,1180:1150}
    adaptations=[];selected={}
    for table,ids in [('K_NPC',npc_ids),('K_MONSTER',monster_ids)]:
        counts=collections.Counter(r['sSid'] for r in source[table])
        if any(counts[sid]!=1 for sid in ids):raise ValueError('Ambiguous selected source definition')
        definitions={r['sSid']:r for r in source[table]}
        if ids-definitions.keys():raise ValueError('Missing source definitions')
        selected[table]=[]
        for sid in sorted(ids):
            row={c:definitions[sid].get(c,0) for c in schemas[table]}
            if table=='K_MONSTER':
                existing=baseline[sid if sid in baseline else fallbacks[sid]]
                if row['sItem']!=existing['sItem']:
                    adaptations.append({'id':sid,'sourceDrop':row['sItem'],'existingDefinition':existing['sSid'],'drop':existing['sItem']})
                row['sItem']=existing['sItem']
            selected[table].append(row)
    lines=['-- Generated by tools/build_moradon_import.py from the owner archive.',
           '-- Zone-21 private definitions only. NEVER execute the original full dump.',
           'DELETE FROM KO_MORADON_IMPORTED_NPC;','DELETE FROM KO_MORADON_IMPORTED_MONSTER;']
    def insert(table,row,columns):
        lines.append('INSERT INTO '+table+' ('+','.join('`'+c+'`' for c in columns)+') VALUES ('+','.join(literal(row.get(c,0)) for c in columns)+');')
    for table in ('K_NPC','K_MONSTER'):
        for row in selected[table]:insert('KO_MORADON_IMPORTED_'+('NPC' if table=='K_NPC' else 'MONSTER'),row,schemas[table])
    lines+=['DELETE FROM K_NPCPOS WHERE ZoneID=21;','DELETE FROM K_OBJECTPOS WHERE ZoneID=21;']
    for row in spawns:
        if not all(0<=row[c]<1024 for c in ('LeftX','TopZ','RightX','BottomZ')):raise ValueError('Spawn outside expanded map')
        insert('K_NPCPOS',row,schemas['K_NPCPOS'])
    for row in objects:
        if not 0<=row['PosX']<1024 or not 0<=row['PosZ']<1024:raise ValueError('Object outside expanded map')
        insert('K_OBJECTPOS',row,schemas['K_OBJECTPOS'])
    manifest=dict(archive='0002_data.zip',sha256=hashlib.sha256((ROOT/'0002_data.zip').read_bytes()).hexdigest(),zone=21,
        npcDefinitions=len(npc_ids),monsterDefinitions=len(monster_ids),npcRows=sum(r['ActType']>=100 for r in spawns),
        npcPopulation=sum(r['NumNPC'] for r in spawns if r['ActType']>=100),monsterRows=sum(r['ActType']<100 for r in spawns),
        monsterPopulation=sum(r['NumNPC'] for r in spawns if r['ActType']<100),objects=len(objects),
        preservedLootAdapters=adaptations,missingObjectProxyDefinitions=sorted(object_ids-available_npcs-{0}),
        unsupportedServiceTypes=sorted({r['byType'] for r in selected['K_NPC'] if r['byType'] not in (21,22,24,31)}))
    return {'src/KnightOnline.Database/World/MoradonExactImport.sql':'\n'.join(lines)+'\n',
            'docs/MORADON_EXACT_IMPORT.json':json.dumps(manifest,indent=2)+'\n'}


if __name__=='__main__':
    outputs=build()
    for relative,text in outputs.items():
        path=ROOT/relative
        if '--check' in sys.argv:
            if not path.exists() or path.read_text()!=text:raise SystemExit('Import drift: '+relative)
        else:path.write_text(text)
    print('Moradon exact import '+('verified' if '--check' in sys.argv else 'generated'))
