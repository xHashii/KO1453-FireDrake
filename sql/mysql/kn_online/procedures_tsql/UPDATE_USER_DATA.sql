CREATE PROCEDURE [dbo].[UPDATE_USER_DATA]
@strCharID char(21),
@bNation tinyint,
@bRace tinyint,
@sClass smallint,
@nHair int,
@bRank tinyint,
@bTitle tinyint,
@bLevel tinyint,
@iExp bigint,
@nLoyalty int,
@bFace tinyint,
@bCity tinyint,
@sClanID smallint,
@bFame tinyint,
@sHp smallint,
@sMp smallint,
@sSp smallint,
@bStr tinyint,
@bSta tinyint,
@bDex tinyint,
@bIntel tinyint,
@bCha tinyint,
@bAuthority tinyint,
@sPoints smallint,		
@nCoins int,
@bZone tinyint,
@sBind smallint,
@iPosX int,
@iPosZ int,
@iPosY int,
@dwTime int,
@sQuestCount smallint,
@strSkill varchar(10),
@strItem binary(584),
@strSerial binary(584),
@strQuest binary(600),
@nMannerPoint int,
@nLoyaltyMonthly int
AS

UPDATE USERDATA 
SET Nation			= @bNation, 
	Race			= @bRace, 
	Class			= @sClass, 
	HairRGB			= @nHair, 
	[Rank]			= @bRank, 
	Title			= @bTitle, 
	[Level]			= @bLevel, 
	[Exp]			= @iExp, 
	Loyalty			= @nLoyalty, 
	Face			= @bFace, 
	City			= @bCity, 
	Knights			= @sClanID, 
	Fame			= @bFame, 
	Hp				= @sHp, 
	Mp				= @sMp, 
	Sp				= @sSp, 
	Strong			= @bStr, 
	Sta				= @bSta, 
	Dex				= @bDex, 
	Intel			= @bIntel, 
	Cha				= @bCha, 
	Authority		= @bAuthority, 
	Points			= @sPoints, 
	Gold			= @nCoins, 
	[Zone]			= @bZone, 
	Bind			= @sBind, 
	PX				= @iPosX, 
	PZ				= @iPosZ, 
	PY				= @iPosY, 
	dwTime			= @dwTime, 
	strSkill		= @strSkill, 
	strItem			= @strItem, 
	strSerial		= @strSerial, 
	sQuestCount		= @sQuestCount, 
	strQuest		= @strQuest, 
	MannerPoint		= @nMannerPoint, 
	LoyaltyMonthly	= @nLoyaltyMonthly, 
	dtUpdateTime	= GETDATE() 
WHERE strUserID		= @strCharID
